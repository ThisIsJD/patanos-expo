const fs = require('node:fs')
const crypto = require('node:crypto')

const SNAPSHOT = 'ProjectContext/database/snapshots/P0.02-database-review.json'
const EXPECTED_HASH = '845638c64e5a5f0c4bc3d81343a44d9eec591f2ad4f8aa279ec540b117a6ead2'
const quote = identifier => '"' + identifier.replaceAll('"', '""') + '"'
const literal = value => "'" + value.replaceAll("'", "''") + "'"

function renderBaseline() {
  const raw = fs.readFileSync(SNAPSHOT)
  if (crypto.createHash('sha256').update(raw).digest('hex') !== EXPECTED_HASH) {
    throw new Error('Reviewed snapshot changed; reconcile before regenerating baseline')
  }
  const metadata = JSON.parse(raw.toString())[0].database_review
  const statements = [
    '-- P0.2 reconstruction for EMPTY LOCAL Supabase only; NOT a production migration.',
    '-- Source: reviewed export 2026-10-04; SHA-256 ' + EXPECTED_HASH,
    '-- Retains known P1/P2/P4 permission and transaction defects for regression work.',
    '-- Snapshot omits numeric typmods, identity generation mode and Realtime publication.',
    '-- Uses unbounded numeric and BY DEFAULT identities; qualify against an authorized dump.',
    '-- Managed auth/storage tables are supplied by Supabase, never recreated here.',
    'BEGIN;',
    'SET LOCAL search_path = public, extensions;',
  ]
  const enumTypes = Map.groupBy(metadata.enum_values, entry => entry.type_name)
  for (const [name, values] of enumTypes) {
    statements.push(`CREATE TYPE public.${quote(name)} AS ENUM (${values.map(entry => literal(entry.value)).join(', ')});`)
  }
  const tables = metadata.relations.filter(entry => entry.schema_name === 'public' && entry.kind === 'r')
  for (const table of tables) {
    const columns = metadata.columns.filter(column => column.table_name === table.name).map(column => {
      const type = column.data_type === 'USER-DEFINED' ? 'public.' + quote(column.udt_name) : column.data_type
      let definition = `  ${quote(column.column_name)} ${type}`
      if (column.is_identity === 'YES') definition += ' GENERATED BY DEFAULT AS IDENTITY'
      if (column.is_generated !== 'NEVER') definition += ` GENERATED ALWAYS AS (${column.generation_expression}) STORED`
      else if (column.column_default !== null) definition += ' DEFAULT ' + column.column_default
      if (column.is_nullable === 'NO') definition += ' NOT NULL'
      return definition
    })
    statements.push(`CREATE TABLE public.${quote(table.name)} (\n${columns.join(',\n')}\n);`)
  }
  // All tables first, then keys, then FKs, so reference order cannot break replay.
  const constraints = metadata.constraints.filter(entry => tables.some(table => table.name === entry.table_name))
  for (const foreignKeys of [false, true]) {
    for (const constraint of constraints.filter(entry => entry.definition.startsWith('FOREIGN KEY') === foreignKeys)) {
      statements.push(`ALTER TABLE public.${quote(constraint.table_name)} ADD CONSTRAINT ${quote(constraint.name)} ${constraint.definition};`)
    }
  }
  for (const index of metadata.indexes.filter(entry => !constraints.some(constraint => constraint.name === entry.indexname))) {
    statements.push(index.indexdef + ';')
  }
  for (const fn of metadata.functions) statements.push(fn.definition.trim() + ';')
  for (const trigger of metadata.triggers) {
    statements.push(trigger.definition + ';')
  }
  for (const view of metadata.views) statements.push(`CREATE VIEW public.${quote(view.name)} AS\n${view.definition}`)
  for (const table of tables) {
    if (table.rls_enabled) statements.push(`ALTER TABLE public.${quote(table.name)} ENABLE ROW LEVEL SECURITY;`)
    if (table.rls_forced) statements.push(`ALTER TABLE public.${quote(table.name)} FORCE ROW LEVEL SECURITY;`)
  }
  for (const policy of metadata.policies) {
    const roles = policy.roles.map(role => role === 'public' ? 'PUBLIC' : quote(role)).join(', ')
    let statement = `CREATE POLICY ${quote(policy.policyname)} ON ${quote(policy.schemaname)}.${quote(policy.tablename)} AS ${policy.permissive} FOR ${policy.cmd} TO ${roles}`
    if (policy.qual) statement += ` USING (${policy.qual})`
    if (policy.with_check) statement += ` WITH CHECK (${policy.with_check})`
    statements.push(statement + ';')
  }
  // Preserve the reviewed broad baseline grants; hardening is a separate P1 migration.
  for (const relation of metadata.relations.filter(entry => entry.schema_name === 'public')) {
    statements.push(`GRANT ALL ON TABLE public.${quote(relation.name)} TO anon, authenticated, service_role;`)
  }
  statements.push('GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;')
  statements.push('REVOKE CREATE ON SCHEMA public FROM PUBLIC, anon, authenticated;')
  for (const bucket of metadata.storage_buckets) {
    statements.push(`INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (${literal(bucket.id)}, ${literal(bucket.name)}, ${bucket.public}, NULL, NULL);`)
  }
  statements.push('-- Realtime publication membership was not exported; qualify separately before enabling.')
  statements.push('COMMIT;')
  return (statements.join('\n\n') + '\n').replaceAll('\r\n', '\n')
}

module.exports = { renderBaseline, EXPECTED_HASH }
if (require.main === module) process.stdout.write(renderBaseline())
