const fs = require('node:fs')
const assert = require('node:assert/strict')
const { renderBaseline } = require('./render-baseline.cjs')
const { renderReconciliation } = require('./render-reconciliation.cjs')
const { renderStagingBootstrap } = require('./render-staging-bootstrap.cjs')
const { renderStagingAccess } = require('./render-staging-access.cjs')

const migration = 'supabase/migrations/20261004000000_reviewed_baseline.sql'
assert.equal(fs.readFileSync(migration, 'utf8').replaceAll('\r\n', '\n'), renderBaseline())
const reconciliation = 'supabase/migrations/20261005000000_development_reconciliation.sql'
assert.equal(fs.readFileSync(reconciliation, 'utf8').replaceAll('\r\n', '\n'), renderReconciliation())
const salesGuard = renderReconciliation().match(/DO \$local_only\$[\s\S]*?\$local_only\$;/)[0]
assert(fs.readFileSync('supabase/tests/002_reconciliation.sql', 'utf8').replaceAll('\r\n', '\n').includes(salesGuard), 'SQL regression must exercise the exact migration sales guard')
const seed = fs.readFileSync('supabase/seed.sql', 'utf8')
assert.match(seed, /SYNTHETIC LOCAL/)
assert.match(seed, /admin@patanos\.test/)
assert.match(seed, /cashier@patanos\.test/)
assert.match(seed, /Test Chicken Rice/)
assert.match(seed, /Test Iced Latte/)
assert.match(seed, /SET role = 'admin', is_enabled = true WHERE id = '11111111-1111-4111-8111-111111111111'/)
assert.match(seed, /SET is_enabled = true WHERE id = '22222222-2222-4222-8222-222222222222'/)
assert.equal((seed.match(/OVERRIDING SYSTEM VALUE/g) || []).length, 3)
assert.match(fs.readFileSync('supabase/config.toml', 'utf8'), /enable_signup = false/)
const securityMigration = fs.readFileSync('supabase/migrations/20261005010000_staff_roles_and_reports.sql', 'utf8')
assert.match(securityMigration, /REVOKE ALL ON TABLE public\.profiles FROM PUBLIC, anon, authenticated/)
assert.match(securityMigration, /GRANT UPDATE \(full_name, avatar_url\) ON public\.profiles TO authenticated/)
assert.match(securityMigration, /SECURITY INVOKER SET search_path = ''/)
assert.match(securityMigration, /LOCK TABLE public\.profiles IN SHARE ROW EXCLUSIVE MODE/)
assert.match(securityMigration, /REVOKE ALL ON TABLE public\.daily_sales, public\.category_sales FROM PUBLIC, anon, authenticated/)
const orderMigration = fs.readFileSync('supabase/migrations/20261006000000_order_mutation_boundaries.sql', 'utf8')
assert.match(orderMigration, /REVOKE ALL ON TABLE public\.orders, public\.order_items, public\.order_item_modifiers FROM PUBLIC, anon, authenticated/)
assert.match(orderMigration, /SECURITY INVOKER SET search_path = ''/)
assert.match(orderMigration, /FROM public\.profiles WHERE id = staff_id FOR SHARE/)
assert.match(orderMigration, /sum\(quantity\)::integer AS quantity/)
assert(!orderMigration.includes('greatest(stock_count -'), 'insufficient stock must fail, not clamp')
const lifecycleMigration = fs.readFileSync('supabase/migrations/20261006010000_staff_access_lifecycle.sql', 'utf8')
assert.match(lifecycleMigration, /ADD COLUMN is_enabled boolean NOT NULL DEFAULT false/)
assert.match(lifecycleMigration, /NEW\.is_enabled IS DISTINCT FROM OLD\.is_enabled/)
assert.match(lifecycleMigration, /AS RESTRICTIVE[\s\S]*TO authenticated/)
assert.match(lifecycleMigration, /WHERE id = staff_id AND is_enabled FOR SHARE/)
assert.match(lifecycleMigration, /LOCK TABLE public\.profiles IN SHARE ROW EXCLUSIVE MODE/)
assert.match(lifecycleMigration, /REVOKE ALL ON TABLE patanos_private\.staff_access_audit FROM PUBLIC, anon, authenticated/)
assert.match(lifecycleMigration, /CREATE FUNCTION public\.set_staff_enabled/)
assert.match(lifecycleMigration, /email_confirmed_at IS NOT NULL/)
assert.match(lifecycleMigration, /banned_until IS NULL OR account\.banned_until <= now\(\)/)
for (const operation of ['place_order', 'complete_order', 'cancel_order']) {
  assert.match(orderMigration, new RegExp(`CREATE(?: OR REPLACE)? FUNCTION public\\.${operation}\\(`))
  assert.match(orderMigration, new RegExp(`ALTER FUNCTION public\\.${operation}\\([^;]+OWNER TO postgres;`))
}
for (const report of ['daily_sales', 'category_sales']) {
  assert(securityMigration.includes(`CREATE FUNCTION public.owner_${report}`))
  assert(securityMigration.includes(`REVOKE ALL ON FUNCTION public.owner_${report}(date, date) FROM PUBLIC, anon, authenticated`))
}
assert.equal(fs.readFileSync('supabase/staging/closed-bootstrap.sql', 'utf8').replaceAll('\r\n', '\n'), renderStagingBootstrap())
assert.equal(fs.readFileSync('supabase/staging/controlled-access.sql', 'utf8').replaceAll('\r\n', '\n'), renderStagingAccess())
console.log('Baseline/supplement provenance, reconciliation, P1 boundaries, staging artifacts and synthetic fixture checks passed; no SQL executed.')
